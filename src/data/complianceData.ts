export type ComplianceStatus = 'pass' | 'fail' | 'manual';
export type ComplianceSeverity = 'critical' | 'high' | 'medium' | 'low';
export type CloudProvider = 'aws' | 'azure' | 'gcp' | 'github' | 'k8s';

export interface ComplianceRequirement {
  id: string; // e.g. "8.1"
  code: string; // e.g. "CIS-8.1"
  title: string;
  description: string;
  rationale?: string;
  remediation?: string;
  status: ComplianceStatus;
  severity: ComplianceSeverity;
  providers: CloudProvider[];
  checkId?: string; // Linked to WAFR check for AI fix / Jira / Slack
  resources?: string[];
  manualNote?: string;
}

export interface ComplianceSection {
  id: string; // e.g. "sec-8"
  number: number;
  title: string; // e.g. "8. Audit Log Management"
  description?: string;
  requirements: ComplianceRequirement[];
}

